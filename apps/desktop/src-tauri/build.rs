//! Build script.
//!
//! Besides the regular `tauri_build`, it generates `permissions/main-window.toml`: an
//! ACL permission that lists ALL the commands registered in `generate_handler!`.
//!
//! Why: without an app ACL manifest, Tauri grants custom commands to
//! any webview with a local origin (including a secondary webview served
//! by a custom protocol). With this file the manifest exists, so every
//! command goes through the ACL and is granted only to the capabilities that list it
//! (`capabilities/default.json` → only the `main` window/webview).
//!
//! The list is derived from `src/lib.rs`, the single source of truth: adding a
//! command to `generate_handler!` is enough, there is no second list to keep
//! in sync. If parsing fails the build stops, so the error never
//! reaches runtime as "Command not allowed by ACL".

use std::{fs, path::Path};

const LIB_RS: &str = "src/lib.rs";
const PERMISSION_FILE: &str = "permissions/main-window.toml";
const MARKER: &str = "generate_handler![";

fn main() {
    println!("cargo:rerun-if-changed={LIB_RS}");
    println!("cargo:rerun-if-changed=build.rs");
    generate_main_window_permission();
    tauri_build::build()
}

fn generate_main_window_permission() {
    let src = fs::read_to_string(LIB_RS).expect("build.rs: cannot read src/lib.rs");
    let commands = registered_commands(&src);
    assert!(
        commands.len() > 50,
        "build.rs: only {} commands found in generate_handler!: broken parsing?",
        commands.len()
    );

    let mut out = String::from(
        "# AUTOGENERATED by build.rs from `generate_handler!` in src/lib.rs.\n\
         # DO NOT edit by hand: it is rewritten on every build.\n\n\
         [[permission]]\n\
         identifier = \"main-window-commands\"\n\
         description = \"All of the app's native commands. Grant ONLY to the main webview, never to contexts that host third-party code.\"\n\
         commands.allow = [\n",
    );
    for cmd in &commands {
        out.push_str(&format!("  \"{cmd}\",\n"));
    }
    out.push_str("]\n");

    let path = Path::new(PERMISSION_FILE);
    // Write only if it changed: tauri_build watches `permissions/` and an
    // unconditional rewrite would rerun the build script on every pass.
    if fs::read_to_string(path).ok().as_deref() != Some(out.as_str()) {
        fs::create_dir_all(path.parent().unwrap()).expect("build.rs: mkdir permissions");
        fs::write(path, out).expect("build.rs: write permissions/main-window.toml");
    }
}

/// Extracts the command names (last path segment) from the
/// `generate_handler![ ... ]` block, ignoring line and block comments.
fn registered_commands(src: &str) -> Vec<String> {
    let start = src
        .find(MARKER)
        .expect("build.rs: `generate_handler![` not found in src/lib.rs")
        + MARKER.len();
    let mut depth = 1usize;
    let mut end = start;
    for (i, c) in src[start..].char_indices() {
        match c {
            '[' => depth += 1,
            ']' => {
                depth -= 1;
                if depth == 0 {
                    end = start + i;
                    break;
                }
            }
            _ => {}
        }
    }
    assert!(depth == 0, "build.rs: unclosed generate_handler! block");

    let mut block = String::new();
    let mut in_block_comment = false;
    for line in src[start..end].lines() {
        let mut rest = line;
        loop {
            if in_block_comment {
                match rest.find("*/") {
                    Some(i) => {
                        rest = &rest[i + 2..];
                        in_block_comment = false;
                    }
                    None => break,
                }
            } else {
                let line_c = rest.find("//");
                let block_c = rest.find("/*");
                match (line_c, block_c) {
                    (Some(l), Some(b)) if b < l => {
                        block.push_str(&rest[..b]);
                        rest = &rest[b + 2..];
                        in_block_comment = true;
                    }
                    (None, Some(b)) => {
                        block.push_str(&rest[..b]);
                        rest = &rest[b + 2..];
                        in_block_comment = true;
                    }
                    (Some(l), _) => {
                        block.push_str(&rest[..l]);
                        break;
                    }
                    (None, None) => {
                        block.push_str(rest);
                        break;
                    }
                }
            }
        }
        block.push('\n');
    }

    let mut names: Vec<String> = block
        .split(',')
        .map(str::trim)
        .filter(|s| !s.is_empty())
        .map(|entry| {
            assert!(
                !entry.contains('#'),
                "build.rs: unsupported attribute inside generate_handler!: `{entry}`"
            );
            let name = entry.rsplit("::").next().unwrap().trim();
            assert!(
                !name.is_empty() && name.chars().all(|c| c.is_ascii_alphanumeric() || c == '_'),
                "build.rs: unrecognized entry in generate_handler!: `{entry}`"
            );
            name.to_string()
        })
        .collect();
    names.sort();
    names.dedup();
    names
}
