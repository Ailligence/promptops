// Bundles the Iconify icons the app uses, so it never downloads icons at run time.
//
//   node scripts/build-icons.mjs
//
// Scans src/ for "prefix:name" references of the icon sets installed as
// @iconify-json/* packages, and writes the matching subset to
// src/app/core/icons/icons.generated.ts. Run it after adding an icon; the
// desktop build runs it too.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { createRequire } from 'node:module';

const require = createRequire(import.meta.url);
const { getIcons } = require('@iconify/utils');

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const SRC = path.join(ROOT, 'src');
const OUT = path.join(SRC, 'app/core/icons/icons.generated.ts');

const prefixes = fs
  .readdirSync(path.join(ROOT, 'node_modules/@iconify-json'))
  .filter((dir) => fs.existsSync(path.join(ROOT, 'node_modules/@iconify-json', dir, 'icons.json')));

function* sourceFiles(dir) {
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) yield* sourceFiles(full);
    else if (/\.(ts|html)$/.test(entry.name) && full !== OUT) yield full;
  }
}

const pattern = new RegExp(`\\b(${prefixes.map((p) => p.replace(/-/g, '\\-')).join('|')}):([a-z0-9]+(?:-[a-z0-9]+)*)\\b`, 'g');
const wanted = new Map(prefixes.map((p) => [p, new Set()]));
for (const file of sourceFiles(SRC)) {
  for (const [, prefix, name] of fs.readFileSync(file, 'utf8').matchAll(pattern)) wanted.get(prefix).add(name);
}

const collections = [];
let total = 0;
for (const [prefix, names] of wanted) {
  if (!names.size) continue;
  const set = JSON.parse(fs.readFileSync(path.join(ROOT, 'node_modules/@iconify-json', prefix, 'icons.json'), 'utf8'));
  const subset = getIcons(set, [...names].sort());
  if (!subset) continue;
  const missing = [...names].filter((n) => !subset.icons[n] && !subset.aliases?.[n]);
  // Unknown names are build errors: every rendered icon must be bundled.
  if (missing.length) throw new Error(`[icons] ${prefix}: not found: ${missing.join(', ')}`);
  total += Object.keys(subset.icons).length + Object.keys(subset.aliases ?? {}).length;
  collections.push(subset);
}

const banner = '// Generated by scripts/build-icons.mjs. Do not edit by hand.\n';
fs.mkdirSync(path.dirname(OUT), { recursive: true });
fs.writeFileSync(OUT, `${banner}import type { IconifyJSON } from '@iconify/types';\n\nexport const ICON_COLLECTIONS: IconifyJSON[] = ${JSON.stringify(collections)};\n`);
console.log(`[icons] ${total} icons from ${collections.length} sets -> ${path.relative(ROOT, OUT)} (${(fs.statSync(OUT).size / 1024).toFixed(0)} KB)`);
