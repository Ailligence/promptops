// Third-party notices for the code that ships in PromptOps.
//
//   node scripts/generate-notices.mjs
//
// Writes apps/web/public/THIRD-PARTY-NOTICES.txt, which is bundled with the
// app. It covers:
//   - the Rust crates compiled into the desktop app (cargo metadata, normal
//     and build dependencies, every target), with the license files each crate
//     ships;
//   - the npm packages bundled into the web UI (production dependencies of
//     apps/web, transitively), with their license files;
//   - the icon sets bundled from @iconify-json (apps/web/scripts/build-icons.mjs);
//   - third-party trademarks shown in the UI and the system libraries bundled
//     in the Linux AppImage.
// Run it before a release; the desktop build of the web UI runs it too.
import fs from 'node:fs';
import path from 'node:path';
import { execFileSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const WEB = path.join(ROOT, 'apps/web');
const TAURI = path.join(ROOT, 'apps/desktop/src-tauri');
const OUT = path.join(WEB, 'public/THIRD-PARTY-NOTICES.txt');
const LICENSE_FILE = /^(licen[cs]e|copying|notice|unlicense)([-_.].*)?$/i;

const sections = [];
const rule = '='.repeat(78);

function licenseFiles(dir, depth = 0) {
  if (!fs.existsSync(dir)) return [];
  const out = [];
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const full = path.join(dir, entry.name);
    if (entry.isFile() && LICENSE_FILE.test(entry.name)) out.push(full);
    // Native sources vendored by -sys crates (for example whisper.cpp) keep their license one level down.
    if (entry.isDirectory() && depth === 0 && !/^(src|tests?|benches|examples|target|node_modules|\.)/.test(entry.name)) {
      out.push(...licenseFiles(full, 1));
    }
  }
  return out.sort();
}

// Each distinct license text is printed once, at the end; components point to it.
const texts = new Map();
function textRef(text) {
  const key = text.replace(/\s+/g, ' ').trim();
  if (!texts.has(key)) texts.set(key, { n: texts.size + 1, text: text.trim() });
  return texts.get(key).n;
}

