/** Packages whose license file lives in a sibling package from the same authors. */
const SIBLING_LICENSE = { 'alloc-stdlib': 'alloc-no-stdlib' };
/** License file shipped by another package with the same single license id (canonical texts such as MPL-2.0). */
const sameLicenseFile = new Map();

/** Canonical text when a package ships no license file: MIT or Apache-2.0 from its license expression. */
function canonical(license, holders) {
  const ids = String(license ?? '').split(/\s+(?:OR|AND|\/)\s+|\//).map((x) => x.replace(/[()]/g, '').trim());
  if (ids.includes('MIT')) return MIT(holders);
  if (ids.includes('Apache-2.0')) return APACHE();
  if (ids.includes('BSL-1.0')) return BSL;
  for (const id of ids) if (sameLicenseFile.has(id)) return fs.readFileSync(sameLicenseFile.get(id), 'utf8');
  return null;
}

function entry(title, license, url, files, holders) {
  const lines = [title, `  License: ${license || 'see text'}`];
  if (url) lines.push(`  Source: ${url}`);
  const refs = files.map((f) => textRef(fs.readFileSync(f, 'utf8')));
  if (!refs.length) {
    const text = canonical(license, holders || `the ${title.split(' ')[0]} authors`);
    if (text) refs.push(textRef(text));
    else lines.push(`  Full text: https://spdx.org/licenses/`);
  }
  if (refs.length) lines.push(`  License text: ${refs.map((n) => `[${n}]`).join(', ')}`);
  return lines.join('\n') + '\n';
}

// ── Rust crates ─────────────────────────────────────────────────────────────
const cargo = process.env.CARGO || 'cargo';
function cargoMetadata() {
  try {
    return execFileSync(cargo, ['metadata', '--format-version', '1', '--manifest-path', path.join(TAURI, 'Cargo.toml')], { maxBuffer: 1 << 30 }).toString();
  } catch (err) {
    if (err.code === 'ENOENT') {
      console.error(`generate-notices: \`${cargo}\` was not found. Install Rust (https://rustup.rs) or add ~/.cargo/bin to PATH (or set CARGO), then retry.`);
    } else {
      console.error(`generate-notices: \`${cargo} metadata\` failed: ${String(err.stderr || err.message).trim().split('\n').pop()}`);
    }
    process.exit(1);
  }
}
const meta = JSON.parse(cargoMetadata());
const byId = new Map(meta.packages.map((p) => [p.id, p]));
const nodes = new Map(meta.resolve.nodes.map((n) => [n.id, n]));
const rootId = meta.resolve.root;
const crates = new Set();
const stack = [rootId];
while (stack.length) {
  const id = stack.pop();
  for (const dep of nodes.get(id)?.deps ?? []) {
    const shipped = dep.dep_kinds.some((k) => k.kind === null || k.kind === 'build');
    if (shipped && !crates.has(dep.pkg)) {
      crates.add(dep.pkg);
      stack.push(dep.pkg);
    }
  }
}
const rust = [...crates].map((id) => byId.get(id)).filter(Boolean).sort((a, b) => a.name.localeCompare(b.name) || a.version.localeCompare(b.version));
for (const p of rust) {
  const files = licenseFiles(path.dirname(p.manifest_path));
  if (files.length && p.license && !/ OR | AND |\//.test(p.license) && !sameLicenseFile.has(p.license)) sameLicenseFile.set(p.license, files[0]);
}
const rustDir = (name) => rust.find((x) => x.name === name);
sections.push(`RUST CRATES (${rust.length})\n`);
for (const p of rust) {
  const sibling = SIBLING_LICENSE[p.name] && rustDir(SIBLING_LICENSE[p.name]);
  if (sibling) {
    sections.push(entry(`${p.name} ${p.version}`, p.license, p.repository, licenseFiles(path.dirname(sibling.manifest_path)), ''));
    continue;
  }
  sections.push(entry(`${p.name} ${p.version}`, p.license, p.repository, licenseFiles(path.dirname(p.manifest_path)), (p.authors ?? []).join(', ')));
}

// ── npm packages bundled in the web UI ─────────────────────────────────────
const pkgJson = (dir) => JSON.parse(fs.readFileSync(path.join(dir, 'package.json'), 'utf8'));
function resolveDir(name, fromDir) {
  for (let dir = fromDir; ; dir = path.dirname(dir)) {
    const candidate = path.join(dir, 'node_modules', name);
    if (fs.existsSync(path.join(candidate, 'package.json'))) return candidate;
    if (dir === path.dirname(dir) || dir === ROOT) return null;
  }
}
const npm = new Map();
const queue = Object.keys(pkgJson(WEB).dependencies ?? {}).map((name) => [name, WEB, true]);
// Polyfills named by package in angular.json (for example @angular/localize/init)
// are bundled even though the package is a dev dependency: list the package,
// not the build tooling it depends on.
const angular = JSON.parse(fs.readFileSync(path.join(WEB, 'angular.json'), 'utf8'));
for (const project of Object.values(angular.projects ?? {})) {
  for (const entry of project.architect?.build?.options?.polyfills ?? []) {
    if (/^[./]|^src\//.test(entry)) continue;
    const parts = entry.split('/');
    queue.push([entry.startsWith('@') ? parts.slice(0, 2).join('/') : parts[0], WEB, false]);
  }
}
while (queue.length) {
  const [name, from, follow] = queue.shift();
  const dir = resolveDir(name, from);
  if (!dir || npm.has(dir)) continue;
  const p = pkgJson(dir);
  npm.set(dir, p);
  if (!follow) continue;
  // Required peer dependencies are bundled too (for example @popperjs/core for ng-bootstrap).
  const optionalPeers = new Set(Object.entries(p.peerDependenciesMeta ?? {}).filter(([, m]) => m?.optional).map(([n]) => n));
  const peers = Object.keys(p.peerDependencies ?? {}).filter((n) => !optionalPeers.has(n));
  for (const dep of [...Object.keys(p.dependencies ?? {}), ...peers]) queue.push([dep, dir, true]);
}
const npmList = [...npm.entries()].sort((a, b) => a[1].name.localeCompare(b[1].name));
sections.push(`\nNPM PACKAGES (${npmList.length})\n`);
for (const [dir, p] of npmList) {
  const repo = typeof p.repository === 'string' ? p.repository : p.repository?.url;
  const license = typeof p.license === 'string' ? p.license : p.license?.type;
  sections.push(entry(`${p.name} ${p.version}`, license, repo, licenseFiles(dir), typeof p.author === 'string' ? p.author : p.author?.name));
}

// ── Icon sets bundled from @iconify-json ───────────────────────────────────
const generated = fs.readFileSync(path.join(WEB, 'src/app/core/icons/icons.generated.ts'), 'utf8');
const prefixes = [...new Set([...generated.matchAll(/"prefix":"([a-z0-9-]+)"/g)].map((m) => m[1]))].sort();
sections.push(`\nICON SETS (${prefixes.length})\n`);
for (const prefix of prefixes) {
  const dir = path.join(WEB, 'node_modules/@iconify-json', prefix);
  const info = JSON.parse(fs.readFileSync(path.join(dir, 'info.json'), 'utf8'));
  const author = info.author ? `${info.author.name}${info.author.url ? ` (${info.author.url})` : ''}` : 'see source';
  const lines = [rule, `${info.name} (Iconify prefix "${prefix}")`, `Author: ${author}`, `License: ${info.license?.title ?? info.license?.spdx}${info.license?.url ? ` (${info.license.url})` : ''}`];
  if (/^CC-BY/i.test(info.license?.spdx ?? '')) lines.push('Attribution: icons from this set are used unchanged in the PromptOps user interface.');
  lines.push('');
  const refs = licenseFiles(dir).map((f) => textRef(fs.readFileSync(f, 'utf8')));
  if (refs.length) lines.push(`License text: ${refs.map((n) => `[${n}]`).join(', ')}`);
  sections.push(lines.join('\n'));
}

